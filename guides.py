GUIDE_ORDER = ['iphone', 'android', 'windows', 'mac', 'tv']

GUIDE_TILES = {
    'iphone':  ('iPhone', 'iOS 15 и новее, iPad тоже'),
    'android': ('Android', 'телефоны и планшеты'),
    'windows': ('Windows', '10 и 11, режим TUN'),
    'mac':     ('Mac', 'macOS 13 Ventura и новее'),
    'tv':      ('Телевизор', 'Android TV, импорт по QR'),
}


@guides.route('/guide')
def index():
    """Указатель инструкций: собирает ссылочный вес и ловит общий запрос
    «как настроить vpn»."""
    tiles = [(slug, *GUIDE_TILES[slug]) for slug in GUIDE_ORDER]
    return render_template('guides_index.html', tiles=tiles)


@guides.route('/guide/<slug>')
def guide(slug):
    data = GUIDES.get(slug)
    if not data:
        abort(404)
    others = [(s, *GUIDE_TILES[s]) for s in GUIDE_ORDER if s != slug]
    # Копия с подставленными числами: сам GUIDES не трогаем, он общий
    # для всех запросов и переживает перезагрузку страницы
    page = dict(data)
    page['faq'] = [(q, _fill(a)) for q, a in data['faq']]
    page['steps'] = [(t, [_fill(x) for x in paras]) for t, paras in data['steps']]
    return render_template('guide.html', g=page, others=others)


